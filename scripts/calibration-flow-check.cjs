const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const { media, fixture, finishTask } = require('./gaze-upgrade-browser-check.cjs');
const base = process.env.HIKE_URL || 'http://127.0.0.1:5177';
(async () => {
  const out = path.resolve(process.env.CHECK_OUTPUT || 'docs/acceptance/easy-entry'); fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-webgpu', '--ignore-gpu-blocklist'] });
  const report = { input: 'Synthetic camera/Worker; not human accuracy or real inference performance', checks: [], errors: [] };
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    await context.addInitScript(media); await context.addInitScript(fixture);
    // A camera processing at ~11 Hz must not lose 25% of its valid samples to a 15 Hz denominator.
    await context.addInitScript(() => {
      const nativeInterval = window.setInterval.bind(window);
      window.setInterval = (fn, ms, ...args) => nativeInterval(fn, Math.abs(ms - 1000 / 15) < 1 ? 1000 / 11.7 : ms, ...args);
    });
    const page = await context.newPage(); page.on('pageerror', e => report.errors.push(e.message));
    await page.goto(base); await page.locator('#hike-setup').click();
    await page.locator('[data-action="fullscreen"]').click();
    await page.waitForFunction(() => !!document.fullscreenElement);
    await page.locator('[data-action="start"]').click();
    await page.waitForFunction(() => !document.querySelector('[data-action="guided"]').disabled);
    await page.evaluate(() => { window.__fixture.validationOffset = { x: .16, y: .08 }; window.__fixture.missingScreenTargets = ['edge00', 'away0']; });
    await page.locator('[data-action="guided"]').click();
    await page.waitForFunction(() => document.querySelector('.gaze-task-progress').textContent.startsWith('3 /'));
    const progress = await page.locator('.gaze-task-progress').innerText();
    await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }); document.dispatchEvent(new Event('visibilitychange')); });
    await page.waitForTimeout(500);
    assert.equal(await page.locator('.gaze-task-progress').innerText(), progress);
    assert.match(await page.locator('.gaze-task-instruction').innerText(), /已暂停/);
    await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => false }); document.dispatchEvent(new Event('visibilitychange')); });
    await finishTask(page, 180000);
    assert.equal(await page.locator('[data-action="scene"]').isDisabled(), false, await page.locator('.gaze-status').innerText());
    assert.match(await page.locator('.gaze-report').innerText(), /达到位置门槛/);
    assert.match(await page.locator('.gaze-screen-report').innerText(), /达到交互启用条件/);
    console.log('Guided calibration passed at synthetic 11.7 Hz');
    report.checks.push('40-step guided flow: 15 position + 5 independent position + 10 screen calibration + 10 independent screen', 'moderate position offset and 20% unknown screen validation pass the user-authorized easy-entry policy', 'background resumes current point without losing completed targets');
    report.calibration = { position: await page.locator('.gaze-report').innerText(), screen: await page.locator('.gaze-screen-report').innerText(), cadence: await page.locator('.gaze-performance').innerText() };
    await page.screenshot({ path: path.join(out, 'validated-synthetic.png') });
    await page.evaluate(() => { window.__fixture.invalid = true; });
    await page.locator('[data-action="validate"]').click(); await finishTask(page, 20000);
    assert.equal(await page.locator('[data-action="scene"]').isDisabled(), false);
    assert.match(await page.locator('[data-action="scene"]').innerText(), /未达标或未验证/);
    assert.match(await page.locator('.gaze-report').innerText(), /未达门槛/);
    await page.evaluate(() => { window.__fixture.invalid = false; });
    await page.locator('[data-action="validate"]').click(); await finishTask(page, 20000);
    assert.equal(await page.locator('[data-action="scene"]').isDisabled(), false);
    report.checks.push('invalid independent validation keeps optional entry available; retrying validation restores verified entry');
    await page.locator('[data-action="scene"]').click();
    await page.waitForFunction(() => document.querySelector('.hike-hud')?.hidden === false, null, { timeout: 90000 });
    await page.locator('.hike-hud').waitFor({ state: 'visible' }); await page.waitForTimeout(8000);
    assert.match(await page.locator('#hike-state').innerText(), /正在行走/);
    await page.locator('#hike-pause').click();
    await page.waitForFunction(() => document.querySelector('#hike-state').textContent.includes('已暂停'));
    const time = await page.locator('#hike-clock').innerText();
    await page.waitForTimeout(1200); assert.equal(await page.locator('#hike-clock').innerText(), time);
    await page.locator('#hike-pause').click(); await page.waitForTimeout(1000);
    await page.screenshot({ path: path.join(out, 'walking-synthetic.png') });
    await page.locator('#hike-stop').click(); await page.locator('.hike-result').waitFor({ state: 'visible' });
    const downloadPromise = page.waitForEvent('download'); await page.locator('#hike-download').click();
    const download = await downloadPromise, exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
    assert.equal(exported.records.length, 1); assert.equal(exported.records[0].outcome, 'stopped'); assert.ok(exported.records[0].distanceM > 0);
    report.shortRun = { elapsedMs: exported.records[0].elapsedMs, distanceM: exported.records[0].distanceM, averageFps: exported.records[0].averageFps, limitation: 'Short synthetic-input run; not 15-minute joint inference acceptance' };
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('focus-hiking.hikes.v1')).records.length), 1);
    report.checks.push('actual forest entry, gaze walking, pause/resume, finish, local save and JSON download');
    await page.screenshot({ path: path.join(out, 'result-synthetic.png') });
    await page.locator('#hike-again').click(); await page.waitForFunction(() => document.querySelector('.hike-hud')?.hidden === false);
    await page.locator('.hike-hud').waitFor({ state: 'visible' }); await page.waitForTimeout(500); await page.locator('#hike-stop').click();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('focus-hiking.hikes.v1')).records.length), 2);
    await page.locator('.hike-result .hike-exit').click();
    assert.ok(await page.evaluate(() => window.__mediaStops > 0));
    report.checks.push('second trip reuses session calibration, saves once, and home releases camera');
    // Camera-shaped test records never remain as real-camera acceptance data.
    await page.evaluate(() => localStorage.removeItem('focus-hiking.hikes.v1'));
    assert.deepEqual(report.errors, []);
    fs.writeFileSync(path.join(out, 'checks.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
